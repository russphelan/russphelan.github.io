/* Reproduce the two fixed-endpoint Jacobi presentation picks. The seeds were
 * selected by comparing whole-path-normalized field widths near actual roots.
 * This command re-solves and verifies them before writing browser data.
 */
'use strict';
const fs=require('node:fs');
const path=require('node:path');
const S=require('./surface.js');
const Solver=require('./solver.js');
const Jacobi=require('./jacobi.js');
const distance=(p,q)=>Math.hypot(...p.map((v,k)=>v-q[k]));
const recipes=[
  {id:'clear-pinch',title:'Clear first pinch',theta:.9939716507891614,length:12.58339123900981,
    surfaceS:6.011263644726878,hiddenS:5.235987755982989,
    description:'A clear surface pinch follows a hidden-pair focus. This path remains near the original torus.'},
  {id:'neck-return',title:'Return from the second torus',theta:2.7945279452288077,length:13.526064027452893,
    surfaceS:11.285734055163475,hiddenS:10.471975511965978,
    description:'After visiting the second torus, a clear surface pinch follows the second hidden-pair focus on the return path.'}
];
function generate(){
  const model=S.getModel('double'),endpoints=model.endpoints.presentation;
  const data={schemaVersion:1,geometryVersion:model.geometryVersion,normalCurvature:.36,indexCutoff:24,
    surface:'double',endpointPreset:'presentation',endpoints:{p:endpoints.p,q:endpoints.q},
    description:'Two numerically verified examples chosen for visible +1 and +2 events at a fixed whole-path ribbon scale.',
    curves:[],picks:[]};
  for(const recipe of recipes){
    const curve=Solver.shoot(model,endpoints.p,endpoints.q,recipe.theta,recipe.length,
      {maxLength:32,normalCurvature:.36,step:.0075,maxSamples:1201});
    if(!curve||curve.nearConjugate||!curve.verification?.converged||curve.index>24||
      curve.residual>2e-5||curve.refinementError>2e-5)throw Error('Invalid showcase shot: '+recipe.id);
    const fields=Jacobi.prepare(curve,model,.36);
    if(!fields.verification.converged||fields.index!==curve.index||distance(fields.endpoint,endpoints.q)>2e-5||
      fields.endpointEvents.length)throw Error('Showcase Jacobi verification failed: '+recipe.id);
    const nearest=(s,type)=>fields.interiorEvents.filter(e=>e[type]).sort((a,b)=>Math.abs(a.s-s)-Math.abs(b.s-s))[0];
    const surface=nearest(recipe.surfaceS,'surface'),hidden=nearest(recipe.hiddenS,'hidden');
    if(!surface||!hidden||Math.abs(surface.s-recipe.surfaceS)>1e-5||Math.abs(hidden.s-recipe.hiddenS)>1e-5||
      surface.multiplicity!==1||hidden.multiplicity!==2)throw Error('Showcase events changed: '+recipe.id);
    const nearSurfaceRatio=Math.min(...[-.4,.4].map(t=>Math.abs(fields.sampleAt(surface.s+t).j)/fields.maxSurfaceAmplitude));
    const atHiddenRatio=Math.abs(fields.sampleAt(hidden.s).j)/fields.maxSurfaceAmplitude;
    curve.id='showcase-'+recipe.id;curve.surface='double';curve.endpointPreset='presentation';
    curve.showcase={id:recipe.id,seed:{theta:recipe.theta,length:recipe.length},
      recheck:{endpointError:distance(fields.endpoint,endpoints.q),...fields.verification}};
    data.curves.push(curve);
    data.picks.push({id:recipe.id,title:recipe.title,description:recipe.description,curveId:curve.id,
      surfaceEventS:surface.s,hiddenEventS:hidden.s,startS:Math.max(0,hidden.s-.85),
      ribbon:{mode:'amplitude',halfWidth:.22,power:.5},
      visibility:{nearSurfaceRatio,atHiddenRatio,offset:.4,maxSurfaceAmplitude:fields.maxSurfaceAmplitude},
      surfaceEvents:fields.interiorEvents.filter(e=>e.surface).map(e=>e.s),
      hiddenEvents:fields.interiorEvents.filter(e=>e.hidden).map(e=>e.s)});
    console.log(`${recipe.title}: index ${curve.index}, L ${curve.length.toFixed(6)}, +1 ${surface.s.toFixed(6)}, +2 ${hidden.s.toFixed(6)}`);
  }
  const output='/* Generated by generate-showcases.cjs. Actual fixed-endpoint numerical geodesics. */\n'+
    "(function(root,factory){'use strict';const data=factory();if(typeof module==='object'&&module.exports)module.exports=data;else root.GeodesicShowcaseData=data;}(typeof globalThis!=='undefined'?globalThis:this,function(){return "+JSON.stringify(data)+';}));\n';
  const target=path.join(__dirname,'showcase-data.js'),temporary=target+'.tmp';
  fs.writeFileSync(temporary,output);fs.renameSync(temporary,target);
  return data;
}
if(require.main===module)generate();
module.exports={generate,recipes};
