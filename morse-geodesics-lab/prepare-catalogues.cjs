/* Regenerate lazily loaded starter files without rewriting the legacy fixture.
 * Existing connected-sum samples are copied at full double precision; new torus
 * shots use the same solver and verification thresholds as live search. */
'use strict';
const fs=require('node:fs'),path=require('node:path');
const S=require('./surface.js'),G=require('./solver.js'),Store=require('./search-store.js');
const configurations=['torus','double','triple'].flatMap(surface=>['default','alternate'].map(preset=>[surface,preset]));

function seedTotal(options,endpoints){
  const model=S.getModel(options.surface),maximum=options.maxLength||model.searchMaxLength||
    ((model.genus||model.count||1)>=3?42:32);
  const d=Math.hypot(...endpoints.p.map((v,i)=>v-endpoints.q[i]));
  const first=Math.min(maximum,d*1.08+.15),lengths=[first,d+3,d+6,d+10,d+16,maximum*.94];
  if(options.quality==='extended')lengths.push(d+13,maximum*.76);
  const count=options.quality==='extended'?44:28;
  return 4+count*new Set(lengths.map(x=>Math.round(Math.max(first,Math.min(maximum,x))*100)/100)).size;
}
function validate(entry,surface,preset){
  const model=S.getModel(surface),endpoints=model.endpoints[preset];
  const distance=(a,b)=>Math.hypot(...a.map((v,i)=>v-b[i]));
  if(!entry.curves.length)throw new Error('No verified starter paths for '+surface+':'+preset);
  for(const curve of entry.curves){
    if(curve.geometryVersion!==model.geometryVersion||curve.nearConjugate||
      !(curve.residual>=0&&curve.residual<=2e-5)||!(curve.refinementError>=0&&curve.refinementError<=2e-5)||
      distance(curve.points[0],endpoints.p)>1e-8||distance(curve.points.at(-1),endpoints.q)>2e-5)
      throw new Error('An unverified starter path was rejected for '+surface+':'+preset);
  }
}
function write(surface,preset,entry){
  validate(entry,surface,preset);
  const directory=path.join(__dirname,'catalogues');fs.mkdirSync(directory,{recursive:true});
  const file=path.join(directory,surface+'-'+preset+'.json'),temporary=file+'.tmp';
  fs.writeFileSync(temporary,JSON.stringify({schemaVersion:1,...entry}));fs.renameSync(temporary,file);
  return fs.statSync(file).size;
}
function buildStarterData(catalogues){
  const data={schemaVersion:1,catalogues:{}};
  for(const [surface,preset]of configurations){
    const key=surface+':'+preset,entry=catalogues[key],model=S.getModel(surface);
    if(!entry||entry.geometryVersion!==model.geometryVersion||entry.normalCurvature!==.36)
      throw new Error('Missing current starter catalogue for '+key);
    const config={surface,endpointPreset:preset,geometryVersion:model.geometryVersion,
      solverVersion:G.solverVersion,normalCurvature:entry.normalCurvature,endpoints:model.endpoints[preset]};
    const curves=entry.curves.filter(curve=>Store.validateCurve(curve,config)).slice()
      .sort((a,b)=>a.length-b.length||a.theta-b.theta).slice(0,2);
    if(curves.length!==2)throw new Error('Two validated starter paths are required for '+key);
    data.catalogues[key]={geometryVersion:entry.geometryVersion,normalCurvature:entry.normalCurvature,
      endpoints:entry.endpoints,searchOptions:entry.searchOptions,curves};
  }
  return data;
}
function writeStarter(directory=__dirname){
  const catalogues=Object.fromEntries(configurations.map(([surface,preset])=>[surface+':'+preset,
    JSON.parse(fs.readFileSync(path.join(directory,'catalogues',surface+'-'+preset+'.json'),'utf8'))]));
  const data=buildStarterData(catalogues);
  // Exact tuple packing removes repeated sample keys, never numeric precision.
  // Expand before exposing the public catalogue so all consumers stay unchanged.
  const packed={...data,catalogues:Object.fromEntries(Object.entries(data.catalogues).map(([key,entry])=>
    [key,{...entry,curves:entry.curves.map(curve=>({...curve,jacobi:curve.jacobi.map(({s,j,jPrime,tangent})=>[s,j,jPrime,...tangent])}))}]))};
  const source='/* Two shortest verified paths per configuration; generated by prepare-catalogues.cjs.\n'+
    ' * Full-precision samples remain available if asynchronous catalogue loading fails. */\n'+
    '(function(root,factory){\'use strict\';const data=factory();'+
    'if(typeof module===\'object\'&&module.exports)module.exports=data;'+
    'else root.GeodesicStarterData=data;}(typeof globalThis!==\'undefined\'?globalThis:this,function(){const data='+
    JSON.stringify(packed)+';for(const entry of Object.values(data.catalogues))for(const curve of entry.curves)curve.jacobi=curve.jacobi.map(([s,j,jPrime,...tangent])=>({s,j,jPrime,tangent}));return data;}));\n';
  const file=path.join(directory,'starter-data.js'),temporary=file+'.tmp';
  fs.writeFileSync(temporary,source);fs.renameSync(temporary,file);return fs.statSync(file).size;
}
function writeScriptCatalogues(directory=__dirname){
  return configurations.map(([surface,preset])=>{
    const key=surface+':'+preset,stem=path.join(directory,'catalogues',surface+'-'+preset);
    const entry=JSON.parse(fs.readFileSync(stem+'.json','utf8'));validate(entry,surface,preset);
    const source='/* Full-precision local-file catalogue; generated by prepare-catalogues.cjs. */\n'+
      '(function(root){\'use strict\';(root.GeodesicCatalogueEntries||(root.GeodesicCatalogueEntries=Object.create(null)))['+
      JSON.stringify(key)+']='+JSON.stringify(entry)+';}(typeof globalThis!==\'undefined\'?globalThis:this));\n';
    const file=stem+'.js',temporary=file+'.tmp';fs.writeFileSync(temporary,source);fs.renameSync(temporary,file);
    return {key,bytes:fs.statSync(file).size};
  });
}
async function main(){
  const legacy=require('./catalogue-data.js');
  for(const [key,entry]of Object.entries(legacy.catalogues)){
    const [surface,preset]=key.split(':'),total=seedTotal(entry.searchOptions,entry.endpoints);
    const coverage=entry.coverage||{quality:entry.searchOptions.quality,round:entry.searchOptions.round,nextSeed:total,total,stopReason:'complete'};
    console.log(key,entry.curves.length,'paths,',write(surface,preset,{...entry,coverage}),'bytes');
  }
  for(const preset of ['default','alternate']){
    const existingPath=path.join(__dirname,'catalogues','torus-'+preset+'.json');
    if(fs.existsSync(existingPath)){
      const existing=JSON.parse(fs.readFileSync(existingPath,'utf8'));
      if(existing.geometryVersion===S.getModel('torus').geometryVersion){
        validate(existing,'torus',preset);
        console.log('torus:'+preset,existing.curves.length,'unchanged verified paths retained');continue;
      }
    }
    const surface='torus',model=S.getModel(surface),endpoints=model.endpoints[preset];
    const options={surface,endpointPreset:preset,normalCurvature:.36,quality:'standard',round:0,maxCurves:36};
    let progress={completed:0,total:seedTotal(options,endpoints)};const started=Date.now();
    const curves=await G.search(options,()=>{},value=>{progress=value;});
    const coverage=curves.searchProgress||{quality:'standard',round:0,nextSeed:progress.completed,total:progress.total,
      stopReason:progress.completed>=progress.total?'complete':'curve-limit'};
    const entry={geometryVersion:model.geometryVersion,normalCurvature:.36,endpoints,searchOptions:options,coverage,curves};
    console.log(surface+':'+preset,curves.length,'paths,',write(surface,preset,entry),'bytes in',(Date.now()-started)/1000,'s');
  }
  console.log('Compact startup bank:',writeStarter(),'bytes');
  console.log('Local-file catalogues:',writeScriptCatalogues());
}
if(require.main===module)main().catch(error=>{console.error(error);process.exitCode=1;});
module.exports={seedTotal,validate,write,buildStarterData,writeStarter,writeScriptCatalogues};
