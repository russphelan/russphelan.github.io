/* Generate one content-verified offline release after app edits. */
'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=__dirname,hash=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
function generate({write=true}={}){
  const indexPath=path.join(root,'index.html'),workerPath=path.join(root,'service-worker.js'),html=fs.readFileSync(indexPath,'utf8'),worker=fs.readFileSync(workerPath,'utf8');
  const meta=/<meta name="offline-release" content="[^"]*">/;
  if(!meta.test(html))throw Error('The offline-release meta tag is missing.');
  const normalizedHTML=html.replace(meta,'<meta name="offline-release" content="BUILD">'),normalizedWorker=worker.replace(/const RELEASE = '[^']*';/,"const RELEASE = 'BUILD';"),files=new Map();
  function add(url){
    const parsed=new URL(url,'https://offline.invalid/app/');
    if(parsed.origin!=='https://offline.invalid'||!parsed.pathname.startsWith('/app/'))throw Error('Offline assets must stay inside the app.');
    const relative=decodeURIComponent(parsed.pathname.slice(5)),filename=path.join(root,relative);
    if(!fs.statSync(filename).isFile())throw Error('Missing offline asset: '+relative);
    const key='./'+relative+parsed.search;
    let entry=files.get(relative);if(!entry){entry={file:relative,urls:[],bytes:relative==='index.html'?Buffer.from(normalizedHTML):fs.readFileSync(filename)};files.set(relative,entry);}
    if(!entry.urls.includes(key))entry.urls.push(key);
  }
  add('./index.html');
  for(const match of html.matchAll(/(?:src|href)="(\.\/[^"#]+)"/g))add(match[1]);
  const manifestPath=path.join(root,'manifest.webmanifest');
  if(fs.existsSync(manifestPath))for(const icon of JSON.parse(fs.readFileSync(manifestPath,'utf8')).icons||[])add(icon.src);
  const loader=fs.readFileSync(path.join(root,'catalogue-loader.js'),'utf8'),catalogueVersion=loader.match(/version='([^']+)'/)?.[1];
  if(!catalogueVersion)throw Error('Catalogue version was not located.');
  for(const surface of ['torus','double','triple'])for(const preset of ['default','alternate'])add('./catalogues/'+surface+'-'+preset+'.json?v='+encodeURIComponent(catalogueVersion));
  const workerURLs=new Set();
  for(const name of ['app.js','search-worker-factory.js'])for(const match of fs.readFileSync(path.join(root,name),'utf8').matchAll(/workerURL\s*[:=]\s*['"](\.\/[^'"]+)['"]/g))workerURLs.add(match[1]);
  if(workerURLs.size!==2)throw Error('Both worker entry points are required.');
  for(const url of workerURLs){
    add(url);
    const text=fs.readFileSync(path.join(root,url.split('?')[0]),'utf8');
    for(const call of text.matchAll(/importScripts\(([^)]+)\)/g))for(const match of call[1].matchAll(/['"](\.\/[^'"]+)['"]/g))add(match[1]);
  }
  const sorted=[...files.values()].sort((a,b)=>a.file.localeCompare(b.file));
  const version=hash(normalizedWorker+'\n'+JSON.stringify(sorted.map(a=>({file:a.file,urls:a.urls.slice().sort(),sha256:hash(a.bytes)})))).slice(0,20);
  const finalHTML=html.replace(meta,'<meta name="offline-release" content="'+version+'">');
  const assets=sorted.map(a=>{const bytes=a.file==='index.html'?Buffer.from(finalHTML):a.bytes;return {urls:a.urls.slice().sort(),size:bytes.length,sha256:hash(bytes)};});
  const manifest={schemaVersion:1,version,totalBytes:assets.reduce((sum,a)=>sum+a.size,0),assets};
  const output='/* Generated by prepare-offline.cjs. Complete content-verified app release. */\nself.GeodesicOfflineAssets = '+JSON.stringify(manifest,null,2)+';\n';
  const finalWorker=worker.replace(/const RELEASE = '[^']*';/,"const RELEASE = '"+version+"';");
  const stale=fs.readFileSync(indexPath,'utf8')!==finalHTML||worker!==finalWorker||!fs.existsSync(path.join(root,'offline-assets.js'))||fs.readFileSync(path.join(root,'offline-assets.js'),'utf8')!==output;
  if(write){fs.writeFileSync(indexPath,finalHTML);fs.writeFileSync(workerPath,finalWorker);fs.writeFileSync(path.join(root,'offline-assets.js'),output);}
  return {manifest,stale};
}
if(require.main===module){const check=process.argv.includes('--check'),result=generate({write:!check});console.log(result.manifest.assets.length+' offline files; '+(result.manifest.totalBytes/1048576).toFixed(1)+' MiB; release '+result.manifest.version);if(check&&result.stale){console.error('Offline release files are stale; run prepare-offline.cjs.');process.exitCode=1;}}
module.exports={generate};
