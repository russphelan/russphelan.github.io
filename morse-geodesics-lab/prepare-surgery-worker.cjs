/* Bundle the canonical preparation sources for a local-file Blob worker. */
'use strict';
const fs=require('node:fs'),path=require('node:path');
function buildSource(directory=__dirname){
  const collar=fs.readFileSync(path.join(directory,'compact-collar.js'),'utf8');
  const surface=fs.readFileSync(path.join(directory,'surface.js'),'utf8');
  const surgery=fs.readFileSync(path.join(directory,'surgery.js'),'utf8');
  const protocol=fs.readFileSync(path.join(directory,'surgery-preparation-worker.js'),'utf8');
  const imports=protocol.match(/^importScripts\([^\n]+\);\r?\n/gm);
  if(imports?.length!==1)throw new Error('The canonical preparation worker must contain exactly one dependency import.');
  return collar+'\n'+surface+'\n'+surgery+'\n'+protocol.replace(imports[0],'');
}
function write(directory=__dirname){
  const source=buildSource(directory);
  const output='/* Generated by prepare-surgery-worker.cjs from the canonical preparation sources. */\n'+
    '(function(root,factory){\'use strict\';const source=factory();'+
    'if(typeof module===\'object\'&&module.exports)module.exports=source;'+
    'else root.GeodesicSurgeryWorkerSource=source;}(typeof globalThis!==\'undefined\'?globalThis:this,function(){return '+
    JSON.stringify(source)+';}));\n';
  const file=path.join(directory,'surgery-worker-source.js'),temporary=file+'.tmp';
  fs.writeFileSync(temporary,output);fs.renameSync(temporary,file);
  return fs.statSync(file).size;
}
if(require.main===module)console.log('File-launch surgery worker:',write(),'bytes');
module.exports={buildSource,write};
