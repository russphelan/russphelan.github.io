/* Offline regeneration for the current connected-sum geometry. The unchanged
 * torus catalogue is preserved by prepare-catalogues.cjs. No tolerances are
 * relaxed: every stored trajectory is endpoint-matched and step-verified. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const surfaces = require('./surface.js');
const solver = require('./solver.js');
const configurations=['double','triple'].flatMap(surface=>['default','alternate'].map(preset=>[surface,preset]));
const distance=(p,q)=>Math.hypot(...p.map((v,i)=>v-q[i]));
function validate(curve,model,endpoints){
  return curve.geometryVersion===model.geometryVersion&&!curve.nearConjugate&&
    curve.verification?.converged&&curve.residual>=0&&curve.residual<=2e-5&&
    curve.refinementError>=0&&curve.refinementError<=2e-5&&
    distance(curve.points[0],endpoints.p)<=1e-8&&distance(curve.points.at(-1),endpoints.q)<=2e-5;
}
async function compute(surface,endpointPreset){
  const model=surfaces.getModel(surface),endpoints=model.endpoints[endpointPreset];
  if(!configurations.some(([s,p])=>s===surface&&p===endpointPreset))throw Error('Unknown connected exploration configuration.');
  // Finish the standard finite seed bank rather than truncating it at 48 paths.
  const options={surface,endpointPreset,normalCurvature:.36,quality:'standard',round:0,maxCurves:256};
  const started=Date.now();let nextReport=0;
  // Old shots are only initial guesses. Re-solve them against the new surface
  // and endpoints; never carry old coordinates, fields, or indices forward.
  const previous=require('./catalogue-data.js').catalogues[surface+':'+endpointPreset]?.curves||[];
  const seeded=[];
  for(const [i,guess]of previous.entries()){
    const curve=solver.shoot(model,endpoints.p,endpoints.q,guess.theta,guess.length,
      {maxLength:model.count>=3?42:32,step:.02,normalCurvature:.36});
    if(curve&&validate(curve,model,endpoints)&&!seeded.some(other=>solver.duplicate(other,curve))){
      Object.assign(curve,{surface,endpointPreset,
        id:`${surface}-${endpointPreset}-${Math.round(curve.theta*1e6)}-${Math.round(curve.length*1e5)}`});
      seeded.push(curve);
    }
    if(i%10===0||i===previous.length-1)console.log(`${surface}:${endpointPreset}: re-solved ${i+1}/${previous.length} previous seeds, ${seeded.length} accepted`);
  }
  const shots=await solver.search({...options,existing:seeded},()=>{},progress=>{
    if(progress.completed>=nextReport||progress.stopReason){
      console.log(`${surface}:${endpointPreset}: ${progress.completed}/${progress.total} seeds, ${progress.accepted} accepted, ${((Date.now()-started)/1000).toFixed(1)}s`);
      nextReport=progress.completed+20;
    }
  });
  const curves=seeded.concat(shots.filter(curve=>validate(curve,model,endpoints)));
  if(curves.length<2)throw Error('Fewer than two verified trajectories for '+surface+':'+endpointPreset);
  if(curves.length!==shots.length+seeded.length)console.log('Rejected '+(shots.length+seeded.length-curves.length)+' ambiguous or unverified shots.');
  return broaden({geometryVersion:model.geometryVersion,normalCurvature:.36,endpoints:{p:endpoints.p,q:endpoints.q},
    searchOptions:options,coverage:shots.searchProgress,curves},surface,endpointPreset);
}
async function broaden(entry,surface,endpointPreset){
  const model=surfaces.getModel(surface),endpoints=model.endpoints[endpointPreset],started=Date.now();let nextReport=0;
  const options={surface,endpointPreset,normalCurvature:.36,quality:'extended',round:0,maxCurves:256};
  const shots=await solver.search({...options,existing:entry.curves},()=>{},progress=>{
    if(progress.completed>=nextReport||progress.stopReason){
      console.log(`${surface}:${endpointPreset}: extended ${progress.completed}/${progress.total}, ${progress.accepted} additional, ${((Date.now()-started)/1000).toFixed(1)}s`);
      nextReport=progress.completed+40;
    }
  });
  entry.curves.push(...shots.filter(curve=>validate(curve,model,endpoints)));
  entry.supplementalSearches=[{searchOptions:options,coverage:shots.searchProgress}];
  return entry;
}
function writeCombined(catalogues){
  const data={schemaVersion:1,generatedAt:new Date().toISOString(),catalogues};
  const output='/* Generated by recompute-catalogues.cjs for the current geometry and endpoints. */\n'+
    '(function(root,factory){\'use strict\';const data=factory();'+
    'if(typeof module===\'object\'&&module.exports)module.exports=data;'+
    'else root.MorseGeodesicCatalogues=data;}(typeof globalThis!==\'undefined\'?globalThis:this,function(){return '+
    JSON.stringify(data)+';}));\n';
  const file=path.join(__dirname,'catalogue-data.js'),temporary=file+'.tmp';
  fs.writeFileSync(temporary,output);fs.renameSync(temporary,file);console.log('Updated '+file);
}
async function main(){
  const broadenFile=process.argv.find(arg=>arg.startsWith('--broaden='))?.slice('--broaden='.length);
  const single=process.argv.find(arg=>arg.startsWith('--configuration='))?.split('=')[1];
  const output=process.argv.find(arg=>arg.startsWith('--output='))?.slice('--output='.length);
  if(broadenFile){
    if(!output)throw Error('--broaden needs an --output JSON path.');
    const entry=JSON.parse(fs.readFileSync(broadenFile,'utf8'));
    await broaden(entry,entry.searchOptions.surface,entry.searchOptions.endpointPreset);
    fs.writeFileSync(output,JSON.stringify(entry));return;
  }
  if(single){
    if(!output)throw Error('--configuration needs an --output JSON path.');
    const [surface,preset]=single.split(':'),entry=await compute(surface,preset);
    fs.writeFileSync(output,JSON.stringify(entry));return;
  }
  const catalogues={};
  for(const [surface,preset]of configurations)catalogues[surface+':'+preset]=await compute(surface,preset);
  writeCombined(catalogues);
}
if(require.main===module)main().catch(error=>{console.error(error);process.exitCode=1;});
module.exports={compute,broaden,validate,writeCombined,configurations};
