/* Offline, reproducible presentation catalogue. No browser dependencies.
 * Run with Node from any directory. --discover replays the finite multi-start
 * search used to locate the selected route basins; it is not a completeness test.
 * The default command re-solves the selected shots and checks their full Jacobi
 * data before replacing presentation-data.js. No curves are drawn by hand.
 */
'use strict';
const fs=require('node:fs');
const path=require('node:path');
const S=require('./surface.js');
const Solver=require('./solver.js');
const Jacobi=require('./jacobi.js');

const NORMAL_CURVATURE=.36, INDEX_CUTOFF=24;
const endpoints=()=>({p:S.getModel('torus').point(-2.35,0),q:S.getModel('torus').point(2.08,0)});
// Two reflected pairs per stage. First-body and second-body paths avoid every
// later attachment patch, and are independently recomputed on each later model.
const recipes=[
  {group:1,theta:.7537606618380064,length:3.253846659611712},
  {group:1,theta:5.5294246501453586,length:3.253846658420921},
  {group:1,theta:1.153847188629479,length:3.612449889182619},
  {group:1,theta:5.1293381185501055,length:3.6124498891826198},
  {group:2,theta:2.6028441605562236,length:10.057878376776674},
  {group:2,theta:3.6803411466233626,length:10.057878376776674},
  {group:2,theta:2.7945279452288077,length:13.526064027452893},
  {group:2,theta:3.4886573619507785,length:13.526064027452893},
  {group:3,theta:3.1403502685977003,length:25.286720777176207},
  {group:3,theta:3.142835038581886,length:25.286720777176207},
  {group:3,theta:3.139407906163374,length:33.218086241004464},
  {group:3,theta:3.1437774010162123,length:33.218086241004464}
];
const distance=(p,q)=>Math.hypot(...p.map((v,k)=>v-q[k]));

function validate(curve,model,group){
  const {p,q}=endpoints();
  if(!curve||curve.geometryVersion!==model.geometryVersion||curve.nearConjugate||
      curve.index>INDEX_CUTOFF||curve.residual>2e-5||curve.refinementError>2e-5||
      distance(curve.points[0],p)>1e-8||distance(curve.points.at(-1),q)>2e-5||
      !curve.verification?.converged)throw Error('Presentation shot did not pass numerical acceptance.');
  const data=Jacobi.prepare(curve,model,NORMAL_CURVATURE);
  if(!data.verification.converged||data.index!==curve.index||distance(data.endpoint,q)>2e-5)
    throw Error('Presentation Jacobi recheck did not agree with the stored geodesic.');
  const maxX=Math.max(...curve.points.map(p=>p[0]));
  const seam=model.neckSeamX??1.0;
  const maxBody=model.centers.reduce((body,center,i)=>maxX>center-seam?i+1:body,1);
  if(maxBody!==group)throw Error(`Route should reach summand ${group}; actual maximum x is ${maxX}.`);
  // Old paths are retained only when they stay clear of later surgery regions.
  if(group<model.count&&maxX>model.centers[group-1]+seam)
    throw Error('Retained path enters a later attachment region.');
  return {data,maxX,maxBody};
}

function generate(){
  const fixed=endpoints(),result={schemaVersion:1,geometryVersion:S.getModel('torus').geometryVersion,
    geometryVersions:Object.fromEntries(S.modelIds.map(id=>[id,S.getModel(id).geometryVersion])),
    normalCurvature:NORMAL_CURVATURE,indexCutoff:INDEX_CUTOFF,endpoints:fixed,
    description:'A curated, nonexhaustive collection of computed geodesics with fixed endpoints and a common ambient index cutoff.',
    selectionRule:'Two reflected pairs of original paths, two reflected pairs visiting summand 2, then two reflected pairs visiting summand 3.',
    stages:{}};
  for(const surface of S.modelIds){
    const model=S.getModel(surface),curves=[];
    for(const [i,recipe]of recipes.entries()){
      if(recipe.group>model.count)continue;
      const curve=Solver.shoot(model,fixed.p,fixed.q,recipe.theta,recipe.length,
        {maxLength:42,maxSamples:1001,normalCurvature:NORMAL_CURVATURE,step:.0075});
      const {data,maxX,maxBody}=validate(curve,model,recipe.group);
      if(curves.some(other=>Solver.duplicate(other,curve)))throw Error('Duplicate presentation curve.');
      Object.assign(curve,{id:`presentation-${i+1}`,surface,endpointPreset:'presentation',
        presentation:{group:recipe.group,maxBody,maxX,label:recipe.group===1?'Original torus':`Visits summand ${recipe.group}`,
          seed:{theta:recipe.theta,length:recipe.length},
          recheck:{index:data.index,endpointError:distance(data.endpoint,fixed.q),...data.verification}}});
      curves.push(curve);
      console.log(`${surface}: ${curve.id}, index ${curve.index}, length ${curve.length.toFixed(5)}, visits ${maxBody}`);
    }
    result.stages[surface]={geometryVersion:model.geometryVersion,count:curves.length,newCount:curves.filter(c=>c.presentation.group===model.count).length,curves};
  }
  const header='/* Generated by generate-presentation.cjs. Curated numerical examples, not an exhaustive count. */\n';
  // Identical retained numerical records share storage. This is exact factoring,
  // not rounding, resampling, or a substitute for the per-stage checks above.
  const records=[],recordKeys=new Map(),packed={...result,stages:{}};
  for(const [surface,stage]of Object.entries(result.stages))packed.stages[surface]={...stage,curves:stage.curves.map(curve=>{
    const {surface:unused,...record}=curve,key=JSON.stringify(record);
    if(!recordKeys.has(key)){recordKeys.set(key,records.length);records.push(record);}
    return recordKeys.get(key);
  })};
  const output=header+"(function(root,factory){'use strict';const data=factory();if(typeof module==='object'&&module.exports)module.exports=data;else root.GeodesicPresentationData=data;}(typeof globalThis!=='undefined'?globalThis:this,function(){const data="+JSON.stringify(packed)+',records='+JSON.stringify(records)+";for(const [surface,stage]of Object.entries(data.stages))stage.curves=stage.curves.map(i=>({...records[i],surface}));return data;}));\n";
  const target=path.join(__dirname,'presentation-data.js'),temporary=target+'.tmp';
  fs.writeFileSync(temporary,output);fs.renameSync(temporary,target);
  console.log(`Wrote ${target}: ${Object.values(result.stages).map(s=>s.count).join(' / ')} computed examples; index ≤ ${INDEX_CUTOFF}.`);
  return result;
}

function discover(){
  const {p,q}=endpoints();
  for(const surface of S.modelIds){
    const model=S.getModel(surface),found=[],lengths=surface==='torus'?[4,8,12,18]:surface==='double'?[4,8,12,16,20,24,30,36]:[4,8,12,18,24,30,36,42,48];
    for(const length of lengths)for(let n=0;n<40;n++){
      const theta=n*2*Math.PI/40;
      const curve=Solver.shoot(model,p,q,theta,length,{maxLength:54,maxSamples:1201});
      if(!curve||curve.nearConjugate||found.some(c=>Solver.duplicate(c,curve)))continue;
      found.push(curve);
      const maxX=Math.max(...curve.points.map(p=>p[0]));
      console.log(JSON.stringify({surface,seed:{theta,length},theta:curve.theta,length:curve.length,index:curve.index,maxX}));
    }
  }
}
if(require.main===module){try{process.argv.includes('--discover')?discover():generate();}catch(error){console.error(error);process.exitCode=1;}}
module.exports={generate,validate,recipes,endpoints,NORMAL_CURVATURE,INDEX_CUTOFF};
